from __future__ import annotations

from dataclasses import dataclass
from importlib import import_module
from pathlib import Path
from typing import Any, Callable, Mapping
import json
import os

import mcp.types as mcp_types
from mcp.server import Server, ServerRequestContext
from mcp.server.stdio import stdio_server

from .action_transports import mcp_tool_descriptors
from .host_actions import ActionAuthorization, ProviderActionDispatcher

VERSION = '0.6.20-mcp-host'
MCP_AUTH_MODULE_ENV = 'CBCC_MCP_AUTH_MODULE'
SUPPORTED_TRANSPORTS = ('stdio', 'streamable-http')


@dataclass(frozen=True)
class MCPAuthorizationContext:
    transport: str
    method: str
    tool_name: str | None
    action_id: str | None
    permission_scope: str | None
    protocol_version: str | None
    request_id: str | None
    headers: dict[str, str]
    meta: dict[str, Any]


MCPAuthorizationResolver = Callable[[MCPAuthorizationContext], ActionAuthorization | None]


def deny_by_default_mcp_authorization(context: MCPAuthorizationContext) -> ActionAuthorization:
    return ActionAuthorization(actor_id='mcp-anonymous', scopes=frozenset())


def _coerce_authorization(value: Any) -> ActionAuthorization | None:
    if value is None or isinstance(value, ActionAuthorization):
        return value
    if isinstance(value, dict):
        return ActionAuthorization.from_scopes(
            value.get('scopes') or [],
            actor_id=str(value.get('actor_id') or 'mcp-host'),
        )
    raise TypeError('MCP authorization resolver must return ActionAuthorization, dict, or None')


def authorization_resolver_from_environment(*, env: Mapping[str, str] | None = None) -> MCPAuthorizationResolver:
    values = os.environ if env is None else env
    module_name = str(values.get(MCP_AUTH_MODULE_ENV) or '').strip()
    if not module_name:
        return deny_by_default_mcp_authorization
    module = import_module(module_name)
    resolver = getattr(module, 'resolve_mcp_action_authorization', None)
    if not callable(resolver):
        raise TypeError(f'{MCP_AUTH_MODULE_ENV} module must expose resolve_mcp_action_authorization(...)')

    def _resolve(context: MCPAuthorizationContext) -> ActionAuthorization | None:
        value = resolver(
            transport=context.transport,
            method=context.method,
            tool_name=context.tool_name,
            action_id=context.action_id,
            permission_scope=context.permission_scope,
            protocol_version=context.protocol_version,
            request_id=context.request_id,
            headers=dict(context.headers),
            meta=dict(context.meta),
        )
        return _coerce_authorization(value)

    return _resolve


def _json_safe(value: Any) -> Any:
    return json.loads(json.dumps(value, ensure_ascii=False, default=str))


def _ctx_headers(ctx: ServerRequestContext[Any]) -> dict[str, str]:
    headers = getattr(ctx, 'headers', None)
    if headers is None:
        request = getattr(ctx, 'request', None)
        headers = getattr(request, 'headers', None)
    if headers is None:
        return {}
    try:
        return {str(k): str(v) for k, v in headers.items()}
    except Exception:
        return {}


def _ctx_meta(ctx: ServerRequestContext[Any]) -> dict[str, Any]:
    meta = getattr(ctx, 'meta', None)
    return dict(meta) if isinstance(meta, Mapping) else {}


def _transport_name(ctx: ServerRequestContext[Any]) -> str:
    return 'streamable-http' if _ctx_headers(ctx) else 'stdio'


class MCPActionTransportAdapter:
    """Thin MCP adapter over the canonical ProviderActionDispatcher.

    Tool names, descriptions and input schemas are generated by v0.6.18 and remain the single
    source of transport truth. This adapter owns MCP mapping and authorization injection only; it
    does not call ProviderExecutionSurface, ProviderExecutorBridge or ProviderExecutor directly.
    """

    def __init__(
        self,
        dispatcher: ProviderActionDispatcher,
        *,
        authorization_resolver: MCPAuthorizationResolver | None = None,
    ) -> None:
        self.dispatcher = dispatcher
        self.authorization_resolver = authorization_resolver or deny_by_default_mcp_authorization
        descriptors = mcp_tool_descriptors()
        self._descriptors = tuple(descriptors)
        self._by_name = {str(row['name']): row for row in descriptors}

    def descriptors(self) -> list[dict[str, Any]]:
        return _json_safe(list(self._descriptors))

    def input_schema(self, tool_name: str) -> Mapping[str, Any] | None:
        row = self._by_name.get(str(tool_name))
        if row is None:
            return None
        return _json_safe(row['inputSchema'])

    def _authorization_context(
        self,
        ctx: ServerRequestContext[Any],
        *,
        tool_name: str | None,
        descriptor: dict[str, Any] | None,
    ) -> MCPAuthorizationContext:
        return MCPAuthorizationContext(
            transport=_transport_name(ctx),
            method=str(getattr(ctx, 'method', '') or ''),
            tool_name=tool_name,
            action_id=str(descriptor.get('x-cbcc-action-id')) if descriptor else None,
            permission_scope=str(descriptor.get('x-cbcc-permission-scope')) if descriptor else None,
            protocol_version=str(getattr(ctx, 'protocol_version', '') or '') or None,
            request_id=str(getattr(ctx, 'request_id', '') or '') or None,
            headers=_ctx_headers(ctx),
            meta=_ctx_meta(ctx),
        )

    def _resolve_authorization(
        self,
        ctx: ServerRequestContext[Any],
        *,
        tool_name: str | None,
        descriptor: dict[str, Any] | None,
    ) -> ActionAuthorization:
        context = self._authorization_context(ctx, tool_name=tool_name, descriptor=descriptor)
        try:
            authorization = _coerce_authorization(self.authorization_resolver(context))
        except Exception:
            return ActionAuthorization(actor_id='mcp-auth-error', scopes=frozenset())
        return authorization or ActionAuthorization(actor_id='mcp-anonymous', scopes=frozenset())

    def _tool(self, descriptor: dict[str, Any]) -> mcp_types.Tool:
        return mcp_types.Tool(
            name=str(descriptor['name']),
            description=str(descriptor.get('description') or ''),
            input_schema=_json_safe(descriptor['inputSchema']),
        )

    async def list_tools(
        self,
        ctx: ServerRequestContext[Any],
        params: mcp_types.PaginatedRequestParams | None,
    ) -> mcp_types.ListToolsResult:
        authorization = self._resolve_authorization(ctx, tool_name=None, descriptor=None)
        visible = [
            self._tool(row)
            for row in self._descriptors
            if authorization.allows(str(row['x-cbcc-permission-scope']))
        ]
        return mcp_types.ListToolsResult(tools=visible)

    async def call_tool(
        self,
        ctx: ServerRequestContext[Any],
        params: mcp_types.CallToolRequestParams,
    ) -> mcp_types.CallToolResult:
        descriptor = self._by_name.get(str(params.name))
        if descriptor is None:
            raise ValueError(f'Unknown MCP tool: {params.name}')
        authorization = self._resolve_authorization(ctx, tool_name=str(params.name), descriptor=descriptor)
        action_id = str(descriptor['x-cbcc-action-id'])
        envelope = self.dispatcher.dispatch(action_id, dict(params.arguments or {}), authorization)
        safe_envelope = _json_safe(envelope)
        status = str(safe_envelope.get('status') or '').upper()
        is_error = status not in {'SUCCEEDED', 'PENDING'}
        return mcp_types.CallToolResult(
            content=[
                mcp_types.TextContent(
                    type='text',
                    text=json.dumps(safe_envelope, ensure_ascii=False, separators=(',', ':')),
                )
            ],
            structured_content=safe_envelope,
            is_error=is_error,
        )


@dataclass
class CBCCMCPHost:
    server: Server[Any]
    adapter: MCPActionTransportAdapter

    async def run_stdio_async(self) -> None:
        async with stdio_server() as (read_stream, write_stream):
            await self.server.run(
                read_stream,
                write_stream,
                self.server.create_initialization_options(),
            )

    def streamable_http_app(
        self,
        *,
        host: str = '127.0.0.1',
        path: str = '/mcp',
        json_response: bool = True,
        stateless_http: bool = True,
        max_request_body_size: int = 4 * 1024 * 1024,
        **kwargs: Any,
    ) -> Any:
        return self.server.streamable_http_app(
            host=host,
            streamable_http_path=path,
            json_response=bool(json_response),
            stateless_http=bool(stateless_http),
            max_request_body_size=max(1, int(max_request_body_size)),
            **kwargs,
        )


def create_mcp_host(
    dispatcher: ProviderActionDispatcher,
    *,
    authorization_resolver: MCPAuthorizationResolver | None = None,
) -> CBCCMCPHost:
    adapter = MCPActionTransportAdapter(
        dispatcher,
        authorization_resolver=authorization_resolver,
    )
    server = Server(
        'cbcc-provider-actions',
        version=VERSION,
        title='CBCC Provider Actions',
        description='Canonical CBCC provider execution actions exposed through MCP.',
        instructions=(
            'Use provider execute for materialized CBCC provider jobs. '
            'When a result is PENDING, use the returned operation_id with status or resume. '
            'Authorization is host-owned and credentials never belong in tool arguments.'
        ),
        get_tool_input_schema=adapter.input_schema,
        on_list_tools=adapter.list_tools,
        on_call_tool=adapter.call_tool,
    )
    return CBCCMCPHost(server=server, adapter=adapter)


